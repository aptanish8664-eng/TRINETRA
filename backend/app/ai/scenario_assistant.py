def _clean(text: str) -> str:
    redacted, has_coordinates = redact_operator_text(text)
    return "[coordinates omitted]" if has_coordinates else redacted


def clean_request(payload: ScenarioAssistantRequest) -> tuple[dict[str, Any], int]:
    """Redacted provider payload plus its character size; coordinates and direct identifiers never reach the model."""
    snapshot = payload.snapshot.model_dump(mode="json")
    for key in ("title", "description"):
        snapshot[key] = _clean(snapshot[key])
    snapshot["objectives"] = [_clean(item) for item in snapshot["objectives"]]
    snapshot["validation_items"] = [_clean(item) for item in snapshot["validation_items"]]
    snapshot["deploy_blockers"] = [_clean(item) for item in snapshot["deploy_blockers"]]
    for aircraft in snapshot["aircraft"]:
        aircraft["parameters"] = {_clean(str(key)): (_clean(value) if isinstance(value, str) else value)
                                  for key, value in aircraft["parameters"].items()}
        aircraft["missing"] = [_clean(item) for item in aircraft["missing"]]
        for key in ("role", "task_type", "return_mode"):
            if aircraft[key] is not None:
                aircraft[key] = _clean(aircraft[key])
    history = [{"role": turn.role, "content": _clean(turn.content)} for turn in payload.history[-6:]]
    message = _clean(payload.message)
    body = {
        "untrusted_form_state": snapshot, "conversation_history": history, "user_message": message,
        "coordinate_policy": "coordinates are never provided and must never be proposed",
    }
    size = len(message) + sum(len(turn["content"]) for turn in history) + len(str(snapshot))
    return body, size


def message_has_coordinates(payload: ScenarioAssistantRequest) -> bool:
    return redact_operator_text(payload.message)[1]


def sanitize_actions(raw_actions: list[Any], aircraft_count: int, known_indexes: set[int]) -> tuple[list[dict[str, Any]], int]:
    """Convert provider actions into the browser's operation shape, dropping anything unknown or invalid."""
    accepted: list[dict[str, Any]] = []
    dropped = 0
    for raw in raw_actions[:5]:
        action = _sanitize_one(raw, known_indexes)
        if action is None:
            dropped += 1
        else:
            accepted.append(action)
    return accepted, dropped + max(0, len(raw_actions) - 5)


def _safe_text(value: Any, limit: int) -> str | None:
    if not isinstance(value, str):
        return None
    text = value.strip()
    if not text or len(text) > limit:
        return None
    redacted, has_coordinates = redact_operator_text(text)
    if has_coordinates or redacted != text or UNSAFE_CONTENT.search(text):
        return None
    return text


def _is_number(value: Any) -> bool:
    return isinstance(value, (int, float)) and not isinstance(value, bool)


def _sanitize_one(raw: Any, known_indexes: set[int]) -> dict[str, Any] | None:
    if not isinstance(raw, dict):
        return None
    op = raw.get("op")
    if op == "set_objective":
        objective = raw.get("objective")
        return {"op": op, "objective": objective} if isinstance(objective, str) and objective in OBJECTIVES else None
    if op == "set_max_duration":
        minutes = raw.get("minutes")
        return {"op": op, "minutes": minutes} if isinstance(minutes, int) and not isinstance(minutes, bool) and 1 <= minutes <= 1440 else None
    if op == "set_required_uav_count":
        count = raw.get("count")
        return {"op": op, "count": count} if isinstance(count, int) and not isinstance(count, bool) and 1 <= count <= 5 else None
    if op == "set_mission_text":
        field = raw.get("field")
        if field not in MISSION_TEXT_FIELDS:
            return None
        text = _safe_text(raw.get("text_value"), MISSION_TEXT_FIELDS[field])
        return {"op": op, "field": field, "value": text} if text else None
    if op == "set_constraint":
        field, value = raw.get("field"), raw.get("number_value")
        if field in CONSTRAINT_FIELDS and _is_number(value) and 0 < float(value) <= CONSTRAINT_FIELDS[field]:
            return {"op": op, "field": field, "value": value}
        return None
    if op == "set_assignment_field":
        index, field = raw.get("uav_index"), raw.get("field")
        if not isinstance(index, int) or isinstance(index, bool) or index not in known_indexes:
            return None
        if field in ENUM_FIELDS:
            text = raw.get("text_value")
            return {"op": op, "uav_index": index, "field": field, "value": text} if isinstance(text, str) and text in ENUM_FIELDS[field] else None
        if field in INT_FIELDS:
            value = raw.get("number_value")
            low, high = INT_FIELDS[field]
            if _is_number(value) and float(value) == int(value) and low <= int(value) <= high:
                return {"op": op, "uav_index": index, "field": field, "value": int(value)}
            return None
        if field in NUMBER_FIELDS:
            value = raw.get("number_value")
            low, high = NUMBER_FIELDS[field]
            if _is_number(value) and low <= float(value) <= high:
                return {"op": op, "uav_index": index, "field": field, "value": value}
    return None


def safe_reply(reply: str) -> str | None:
    """None when the reply must be replaced (unsafe or contains coordinates)."""
    redacted, has_coordinates = redact_operator_text(reply)
    if has_coordinates or UNSAFE_CONTENT.search(reply):
        return None
    return redacted.strip()
